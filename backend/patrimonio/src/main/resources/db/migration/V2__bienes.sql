-- Relación de bienes: muebles, inmuebles y vehículos

CREATE TABLE bien_mueble (
    id                     BIGSERIAL PRIMARY KEY,
    no_control_inventario  VARCHAR(60) NOT NULL UNIQUE,
    descripcion            VARCHAR(300) NOT NULL,
    marca                  VARCHAR(120),
    modelo                 VARCHAR(120),
    serie                  VARCHAR(120),
    especificaciones       TEXT,
    ubicacion              VARCHAR(250),
    estado                 VARCHAR(60),
    servidor_publico       VARCHAR(200),
    cargo                  VARCHAR(200),
    fecha_resguardo        DATE,
    documento_soporte      VARCHAR(60),
    no_factura             VARCHAR(60),
    expedida_por           VARCHAR(200),
    fecha_factura          DATE,
    costo                  NUMERIC(14, 2),
    area_id                BIGINT NOT NULL REFERENCES area (id),
    activo                 BOOLEAN NOT NULL DEFAULT TRUE,
    creado_por             BIGINT REFERENCES usuario (id),
    creado_en              TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_bien_mueble_area ON bien_mueble (area_id);

CREATE TABLE bien_inmueble (
    id                       BIGSERIAL PRIMARY KEY,
    no_expediente            VARCHAR(60) NOT NULL UNIQUE,
    fecha_revision           DATE,
    colonia                  VARCHAR(150),
    calle                    VARCHAR(200),
    denominacion             VARCHAR(300) NOT NULL,
    tipo_uso                 VARCHAR(150),
    medidas_colindancias     TEXT,
    latitud                  NUMERIC(9, 6),
    longitud                 NUMERIC(9, 6),
    propietarios             VARCHAR(300),
    fecha_adquisicion        DATE,
    fojas                    VARCHAR(60),
    observaciones            TEXT,
    documentacion            TEXT,
    clave_catastral          VARCHAR(60),
    fecha_ultimo_avaluo      DATE,
    valor_terreno            NUMERIC(16, 2),
    valor_construccion       NUMERIC(16, 2),
    valor_total              NUMERIC(16, 2),
    superficie_construccion  NUMERIC(14, 2),
    superficie_predio        NUMERIC(14, 2),
    area_id                  BIGINT NOT NULL REFERENCES area (id),
    activo                   BOOLEAN NOT NULL DEFAULT TRUE,
    creado_por               BIGINT REFERENCES usuario (id),
    creado_en                TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_bien_inmueble_area ON bien_inmueble (area_id);

CREATE TABLE vehiculo (
    id                BIGSERIAL PRIMARY KEY,
    numero            VARCHAR(30),
    no_economico      VARCHAR(60),
    no_inventario     VARCHAR(60) NOT NULL UNIQUE,
    folio_resguardo   VARCHAR(60),
    fecha_revision    DATE,
    marca             VARCHAR(120) NOT NULL,
    version           VARCHAR(120),
    color             VARCHAR(60),
    modelo            VARCHAR(60),
    no_serie          VARCHAR(60) UNIQUE,
    cilindros         VARCHAR(20),
    no_motor          VARCHAR(60),
    placas            VARCHAR(30),
    documentacion     TEXT,
    emisor            VARCHAR(200),
    fecha_factura     DATE,
    folio_factura     VARCHAR(60),
    valor_factura     NUMERIC(14, 2),
    valor_depreciado  NUMERIC(14, 2),
    propiedad         VARCHAR(150),
    condiciones       VARCHAR(250),
    area_id           BIGINT NOT NULL REFERENCES area (id),
    activo            BOOLEAN NOT NULL DEFAULT TRUE,
    creado_por        BIGINT REFERENCES usuario (id),
    creado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_vehiculo_area ON vehiculo (area_id);
